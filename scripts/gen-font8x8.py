#!/usr/bin/env python3
"""gen-font8x8.py — regenerate font/font8x8.cst, the kernel's 8x8 font.

The kernel draws text in two places: the boot screen and the panic screen.
The panic screen shows the last lines of the log, so the font has to cover
every byte the log can contain. The hand-drawn table it replaced had letters,
digits and four punctuation marks; "#14 (page fault)" came out as "14 page
fault", and J, Q, j and q were blank.

This takes printable ASCII (0x20..0x7E) from the IBM VGA 8x8 font as the
console fonts ship it (cp850-8x8: CP850 agrees with ASCII over that range),
the same lineage as the 8x16 console font userspace draws with. Slot 0x7F
holds a hollow box, drawn for every byte outside that range.

    scripts/gen-font8x8.py [PSF] > font/font8x8.cst
"""
import gzip
import struct
import sys

PSF = "/usr/share/kbd/consolefonts/cp850-8x8.psfu.gz"
BOX = [0x00, 0x7E, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00]


def load(path):
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    if data[:4] == b"\x72\xb5\x4a\x86":
        _, _, hdr, _, count, size, height, width = struct.unpack("<8I", data[:32])
    elif data[:2] == b"\x36\x04":
        hdr, count, size, height, width = 4, 512 if data[2] & 1 else 256, data[3], data[3], 8
    else:
        sys.exit(f"{path}: not a PSF font")
    if width != 8 or height != 8 or count < 128:
        sys.exit(f"{path}: need an 8x8 font with at least 128 glyphs, got {width}x{height}x{count}")
    return [list(data[hdr + c * size: hdr + c * size + 8]) for c in range(128)]


def main():
    glyphs = load(sys.argv[1] if len(sys.argv) > 1 else PSF)
    out = []
    w = out.append
    w("// font8x8.cst — the kernel's 8x8 font: printable ASCII, MSB = leftmost pixel.")
    w("//")
    w("// Generated by scripts/gen-font8x8.py from the IBM VGA 8x8 console font; do")
    w("// not edit by hand. 0x20..0x7E are the ASCII glyphs; every other byte draws")
    w("// the hollow box in slot 0x7F, so a stray control or UTF-8 byte in a log line")
    w("// shows up as a box instead of reading past the table.")
    w("")
    w("let is [1024]u8 as font8x8_data;")
    w("")
    w("let is i64 as GLYPH_FIRST = 0x20;")
    w("let is i64 as GLYPH_LAST = 0x7E;")
    w("let is i64 as GLYPH_BOX = 0x7F;")
    w("")
    w("fn set8(off as i64, b0 as i64, b1 as i64, b2 as i64, b3 as i64, b4 as i64, b5 as i64, b6 as i64, b7 as i64) as void {")
    for i in range(8):
        w(f"    font8x8_data[off + {i}] = cast(u8, b{i});")
    w("}")
    w("")
    groups = [(0x20, 0x40), (0x40, 0x60), (0x60, 0x80)]
    for gi, (lo, hi) in enumerate(groups):
        w(f"fn init_{gi}() as void {{")
        for c in range(lo, hi):
            g = BOX if c == 0x7F else glyphs[c]
            if c != 0x7F and not any(g):
                continue
            name = "box" if c == 0x7F else ("'\\''" if c == 0x27 else f"'{chr(c)}'")
            row = ",".join(f"0x{b:02X}" for b in g)
            w(f"    set8(0x{c * 8:03X}, {row}); // {name}")
        w("}")
        w("")
    w("fn init() as void {")
    for gi in range(len(groups)):
        w(f"    init_{gi}();")
    w("}")
    w("")
    w("fn get_glyph(ch as i32) as *u8 {")
    w("    let is i64 as c with mut = cast(i64, ch) & 0xFF;")
    w("    if (c < GLYPH_FIRST || c > GLYPH_LAST) { c = GLYPH_BOX; }")
    w("    return cast(*u8, cast(i64, &font8x8_data) + c * 8);")
    w("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
